#!/usr/bin/env python3
"""Writes dashboard/data.js from the experiment results, so the dashboard shows the real measured numbers."""
import csv
import glob
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "dashboard", "data.js")


def main():
    rows = []
    for path in sorted(glob.glob(os.path.join(HERE, "results", "run-*", "trials.csv"))):
        run = os.path.basename(os.path.dirname(path))[-1].upper()
        for r in csv.DictReader(open(path)):
            r["run"] = run
            rows.append(r)

    moves = []
    for key in sorted({(r["run"], int(r["move"])) for r in rows}):
        g = [r for r in rows if (r["run"], int(r["move"])) == key]
        saw = [r for r in g if r["tremor_reason"] == "0"]
        moves.append({
            "label": f"{key[0]}{key[1]}",
            "movePct": round(float(g[0]["move_pct"]), 2),
            "from": round(float(g[0]["market_before"]), 2),
            "to": round(float(g[0]["market_after"]), 2),
            "staticLoss": round(float(g[0]["static_lp_loss_tusd"]), 2),
            "tremorLoss": round(sum(float(r["tremor_lp_loss_tusd"]) for r in saw) / len(saw), 2) if saw else None,
            "tremorFeeBps": round(sum(float(r["tremor_fee_bps"]) for r in saw) / len(saw), 1) if saw else None,
            "loopS": int(g[0]["loop_block_s"]),
            "baseTx": g[0]["base_swap_tx"],
            "refTx": g[0]["ref_tx"],
        })

    loops = [m["loopS"] for m in moves]
    s_saw = sum(m["staticLoss"] for m in moves)
    t_saw = sum(m["tremorLoss"] or 0 for m in moves)
    s_all = sum(float(r["static_lp_loss_tusd"]) for r in rows)
    t_all = sum(float(r["tremor_lp_loss_tusd"]) for r in rows)
    costs = None
    cpath = os.path.join(HERE, "results", "costs.json")
    if os.path.exists(cpath):
        c = json.load(open(cpath))["summary"]
        costs = {
            "surchargeTusd": round(c["lp_surcharge_tusd_total"]),
            "medianSurchargeBps": round(c["median_surcharge_bps"]),
            "reactPerMove": round(c["per_move"]["react_per_move"], 4),
            "reactiveGasEach": int(c["per_move"]["reactive_gas_each"]),
            "callbackGasEach": int(c["per_move"]["callback_gas_each"]),
            "moves": c["moves"], "trades": c["bot_trades"],
        }
    modes = None
    mpath = os.path.join(HERE, "results", "modes.json")
    if os.path.exists(mpath):
        md = json.load(open(mpath))
        loss = {m: sum(r["arbitrage"][m]["lp_loss_tusd"] for r in md["moves"]) for m in "ABCD"}
        man = (md.get("manipulation") or {}).get("quotes", {})
        labels = {"A": "Static pool", "B": "Gap fee, no direction", "C": "Direction only", "D": "Full Tremor"}
        modes = [{
            "mode": m, "label": labels[m],
            "lossCutPct": round(100 * (1 - loss[m] / loss["A"])) if loss["A"] else 0,
            "ordinaryFeeBps": round(sum(r["quotes"][m]["ordinary_fee_bps"] for r in md["moves"]) / len(md["moves"])),
            "fakePriceFeeBps": round(man.get(m, {}).get("arbitrage_fee_bps", 0)),
        } for m in "ABCD"]
    data = {
        "modes": modes,
        "costs": costs,
        "moves": moves,
        "totals": {
            "moves": len(moves), "trades": len(rows),
            "loopMedianS": statistics.median(loops), "loopMinS": min(loops), "loopMaxS": max(loops),
            "lossCutPct": round(100 * (1 - t_saw / s_saw)),
            "lossCutAllPct": round(100 * (1 - t_all / s_all)),
        },
    }
    with open(OUT, "w") as f:
        f.write("// Generated by experiment/export_dashboard.py from experiment/results. Do not edit by hand.\n")
        f.write("window.TREMOR_RESULTS = " + json.dumps(data, indent=1) + ";\n")
    print(OUT, data["totals"])


if __name__ == "__main__":
    main()
